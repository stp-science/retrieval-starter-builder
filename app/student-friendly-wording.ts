export function polishStudentWording<T extends { q: string; a: string; kind: "short" | "explain" }>(question: T): T {
  const reviewed = studentFriendlyWording[question.q];
  let result = reviewed ? { ...question, ...reviewed } : question;
  if (reviewed && /^(?:Explain|Describe|Compare|Distinguish)\b/.test(result.q)) {
    result = { ...result, kind: "explain" };
  }
  let q = result.q;

  const significance = q.match(/^Explain why “(.+)” matters when carrying out or evaluating a scientific investigation\.$/);
  if (significance) {
    const term = significance[1];
    const plural = /(?:conditions|figures|units|trials|data|measurements|bars)$/.test(term);
    q = `Explain why ${term} ${plural ? "matter" : "matters"} in a scientific investigation.`;
  }
  // State the judgement and the expected explanation explicitly.
  if (q.startsWith("Explain whether ")) {
    q = q.replace(/^Explain whether /, "State whether ")
      .replace(/\bdoes ([a-z]+)\b/g, (_, verb: string) => {
        if (verb === "have") return "has";
        if (/[^aeiou]y$/.test(verb)) return verb.slice(0, -1) + "ies";
        return verb + (/(?:s|sh|ch|x|z|o)$/.test(verb) ? "es" : "s");
      }) + " Explain your answer.";
  }
  return q === result.q ? result : { ...result, q, kind: /^State whether .*Explain your answer\.$/.test(q) ? "explain" : result.kind };
}
